using System.Text.Json.Serialization;

namespace Quizly.Application.Learning;

/// <summary>Vím (know), Nevím (dontKnow), and with "Těžké a Snadné" on: Těžké (hard), Snadné (easy).</summary>
public enum ReviewRating
{
    [JsonStringEnumMemberName("know")]
    Know,

    [JsonStringEnumMemberName("dontKnow")]
    DontKnow,

    [JsonStringEnumMemberName("hard")]
    Hard,

    [JsonStringEnumMemberName("easy")]
    Easy,
}

/// <summary>What the next answer is worth at the current multiplier. Těžké and Snadné are worth a Vím.</summary>
public sealed record PointsValueResponse(int Know, int DontKnow, int Hard, int Easy);

/// <summary>Today's progress toward the daily goal.</summary>
public sealed record TodayResponse(DateOnly Date, int Graded, int Correct, int Goal, bool GoalMet, int Points);

/// <summary>The next multiplier step.</summary>
public sealed record NextMultiplierResponse(decimal Value, int InDays);

/// <summary>A streak that ended; the phone shows the comeback notification on <see cref="BrokenOn"/>.</summary>
public sealed record StreakBrokenResponse(int PreviousStreak, DateOnly BrokenOn);

/// <summary>Balance, streak, multiplier and today's progress (docs/api.md §1.2).</summary>
public sealed record SummaryResponse(
    int Balance,
    int Streak,
    int BestStreak,
    decimal Multiplier,
    NextMultiplierResponse? NextMultiplier,
    TodayResponse Today,
    StreakBrokenResponse? StreakBroken);

/// <summary>Something to celebrate: <c>goalMet</c>, <c>milestone</c> or <c>wishlistReached</c>.</summary>
public sealed record EventResponse(
    string Type,
    [property: JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)] int? Days = null,
    [property: JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)] int? Bonus = null,
    [property: JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)] int? ItemId = null,
    [property: JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)] string? Name = null,
    [property: JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)] int? Price = null)
{
    public static EventResponse GoalMet() => new("goalMet");

    public static EventResponse Milestone(int days, int bonus) => new("milestone", Days: days, Bonus: bonus);

    public static EventResponse WishlistReached(int itemId, string name, int price) =>
        new("wishlistReached", ItemId: itemId, Name: name, Price: price);
}

/// <summary>One answer. <see cref="Id"/> is generated by the phone and makes retries safe.</summary>
public sealed record ReviewItemRequest(Guid Id, int CardId, ReviewRating Rating);

/// <summary>A batch of 1–50 answers in the order they were given.</summary>
public sealed record ReviewBatchRequest(IReadOnlyList<ReviewItemRequest> Reviews);

/// <summary>Outcome of one answer: <c>applied</c>, <c>duplicate</c> or <c>rejected</c> (with a code).</summary>
public sealed record ReviewResultResponse(
    Guid Id,
    string Status,
    [property: JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)] int? PointsAwarded = null,
    [property: JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)] decimal? Multiplier = null,
    [property: JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)] string? Code = null);

/// <summary>Per-answer results, the new summary, next answer values and events.</summary>
public sealed record ReviewBatchResponse(
    IReadOnlyList<ReviewResultResponse> Results,
    SummaryResponse Summary,
    PointsValueResponse Points,
    IReadOnlyList<EventResponse> Events);

/// <summary>One card in the session queue.</summary>
public sealed record SessionCardResponse(int CardId, int DeckId, string Question, string Answer, string Kind);

/// <summary>The session queue: due cards first (most overdue first), then new cards.</summary>
public sealed record SessionResponse(
    int? DeckId,
    decimal Multiplier,
    PointsValueResponse Points,
    int DueCount,
    int NewCount,
    IReadOnlyList<SessionCardResponse> Cards,
    bool FourRatings);

/// <summary>A deck with the user's counts.</summary>
public sealed record AppDeckResponse(
    int Id,
    string Name,
    string Description,
    string Color,
    int TotalCards,
    int DueNow,
    int NewAvailable,
    int MasteredPercent,
    int LearningPercent,
    int UnseenCards);

/// <summary>One card of a deck with the user's status: <c>new</c>, <c>learning</c> or <c>mastered</c> (spec §3.5).</summary>
public sealed record DeckCardResponse(
    int Id,
    string Question,
    string Answer,
    string Status,
    int MasteryPercent,
    int KnowCount,
    int DontKnowCount,
    DateTimeOffset? NextReview);

/// <summary>A deck (with the user's counts) and all its cards in sort order.</summary>
public sealed record DeckCardsResponse(AppDeckResponse Deck, IReadOnlyList<DeckCardResponse> Cards);

/// <summary>All decks and how many new cards are left for today.</summary>
public sealed record AppDeckListResponse(IReadOnlyList<AppDeckResponse> Items, int NewAllowanceLeft);
